\c htxhrms;

SET ROLE hrms_dba;

SET SCHEMA 'hrms';

DROP TABLE IF EXISTS developers CASCADE;

DROP TABLE IF EXISTS tasks CASCADE;

DROP TABLE IF EXISTS skills CASCADE;

DROP TABLE IF EXISTS tasksmapper CASCADE;

DROP TABLE IF EXISTS taskskillsmapper CASCADE;

DROP TABLE IF EXISTS developerskillsmapper CASCADE;

DROP TABLE IF EXISTS sysconfig CASCADE;

CREATE TABLE developers (
    developerid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid VARCHAR(36) NOT NULL UNIQUE,
    version INTEGER NOT NULL DEFAULT 1,
    createdby VARCHAR(20) NOT NULL,
    createddate TIMESTAMP WITHOUT TIME ZONE DEFAULT now() ,
    modifiedby VARCHAR(20) NOT NULL,
    modifieddate TIMESTAMP WITHOUT TIME ZONE DEFAULT now() ,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(320),
    division VARCHAR(255),
    designation VARCHAR(255),
    status VARCHAR(1) NOT NULL
);

CREATE TABLE tasks (
    taskid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid VARCHAR(36) NOT NULL UNIQUE,
    version INTEGER NOT NULL DEFAULT 1,
    createdby VARCHAR(20) NOT NULL,
    createddate TIMESTAMP WITHOUT TIME ZONE DEFAULT now(),
    modifiedby VARCHAR(20) NOT NULL,
    modifieddate TIMESTAMP WITHOUT TIME ZONE DEFAULT now(),
    tasktitle VARCHAR(255) NOT NULL,
    taskdescription TEXT,
    status VARCHAR(1) DEFAULT 'T' NOT NULL,
    parenttaskid BIGINT,
    deleteddate TIMESTAMP WITHOUT TIME ZONE
);

CREATE TABLE skills (
    skillid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid VARCHAR(36) NOT NULL UNIQUE,
    version INTEGER NOT NULL DEFAULT 1,
    createdby VARCHAR(20) NOT NULL,
    createddate TIMESTAMP WITHOUT TIME ZONE DEFAULT now(),
    modifiedby VARCHAR(20) NOT NULL,
    modifieddate TIMESTAMP WITHOUT TIME ZONE DEFAULT now(),
    skillname VARCHAR(255) NOT NULL,
    skilldescription TEXT NOT NULL,
    status VARCHAR(1) NOT NULL
);

CREATE TABLE tasksmapper (
    taskmapperid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version INTEGER NOT NULL DEFAULT 1,
    createdby VARCHAR(20) NOT NULL,
    createddate TIMESTAMP WITHOUT TIME ZONE DEFAULT now(),
    modifiedby VARCHAR(20) NOT NULL,
    modifieddate TIMESTAMP WITHOUT TIME ZONE DEFAULT now(),
    taskid BIGINT NOT NULL,
    developerid BIGINT NOT NULL
);

CREATE TABLE developerskillsmapper (
    skillsmapperid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version INTEGER NOT NULL DEFAULT 1,
    createdby VARCHAR(20) NOT NULL,
    createddate TIMESTAMP WITHOUT TIME ZONE DEFAULT now() ,
    modifiedby VARCHAR(20) NOT NULL,
    modifieddate TIMESTAMP WITHOUT TIME ZONE DEFAULT now(),
    skillid BIGINT NOT NULL,
    developerid BIGINT NOT NULL
);

CREATE TABLE taskskillsmapper (
    skillsmapperid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version INTEGER NOT NULL DEFAULT 1,
    createdby VARCHAR(20) NOT NULL,
    createddate TIMESTAMP WITHOUT TIME ZONE DEFAULT now(),
    modifiedby VARCHAR(20) NOT NULL,
    modifieddate TIMESTAMP WITHOUT TIME ZONE DEFAULT now(),
    taskid BIGINT NOT NULL,
    skillid BIGINT NOT NULL
);

CREATE TABLE sysconfig(
    sysconfigid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version INTEGER NOT NULL DEFAULT 1,
    createdby VARCHAR(20) NOT NULL,
    createddate TIMESTAMP WITHOUT TIME ZONE DEFAULT now(),
    modifiedby VARCHAR(20) NOT NULL,
    modifieddate TIMESTAMP WITHOUT TIME ZONE DEFAULT now(),
    sysconfigname VARCHAR(255) NOT NULL,
    sysconfigvalue VARCHAR(255) NOT NULL
);
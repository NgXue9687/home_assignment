\c htxhrms;

ALTER DATABASE htxhrms OWNER TO hrms_dba;


DROP SCHEMA public CASCADE;
CREATE SCHEMA IF NOT EXISTS hrms AUTHORIZATION hrms_dba;
COMMENT ON SCHEMA hrms IS 'Default Scheme for HTX HRMS';

GRANT USAGE ON SCHEMA hrms to hrms_dba,hrms_dev;

-- Application role access
GRANT CONNECT ON DATABASE htxhrms TO hrms_webapp;
GRANT USAGE ON SCHEMA hrms TO hrms_webapp;

-- DEFAULT Permission for DBA ROLE
ALTER DEFAULT PRIVILEGES FOR ROLE hrms_dba IN SCHEMA hrms
    GRANT SELECT,INSERT,UPDATE,DELETE ON TABLES TO hrms_webapp;
ALTER DEFAULT PRIVILEGES FOR ROLE hrms_dba IN SCHEMA hrms GRANT SELECT,USAGE,UPDATE ON SEQUENCES TO hrms_webapp;

ALTER DEFAULT PRIVILEGES FOR ROLE hrms_dba IN SCHEMA hrms GRANT EXECUTE ON FUNCTIONS TO hrms_webapp;

-- DEFAULT Permission for DEV ROLE
ALTER DEFAULT PRIVILEGES FOR ROLE hrms_dev IN SCHEMA hrms GRANT SELECT ON TABLES TO hrms_webapp;
ALTER DEFAULT PRIVILEGES FOR ROLE hrms_dev IN SCHEMA hrms GRANT SELECT ON SEQUENCES TO hrms_webapp;


